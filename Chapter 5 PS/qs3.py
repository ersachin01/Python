#Can we have a set with 18 (int) and '18' (str) as a value in it?

my_set = {18, '18'}
print(my_set)   
#Yes, we can have a set with both 18 (int) and '18' (str) as values in it. Sets in Python can contain elements of different data types, and they are treated as distinct values. In this case, 18 (int) and '18' (str) are considered different elements in the set.